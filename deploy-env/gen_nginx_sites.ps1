#requires -Version 5.1
# 由环境注册表 registry.sqlite 生成多环境 nginx 站点片段（每 project x env 一个端口）。
# 用法: powershell -NoProfile -ExecutionPolicy Bypass -File gen_nginx_sites.ps1
$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
# Python 在 Windows 下管道 stdout 默认走 ANSI(GBK)，中文路径会乱码；强制 UTF-8 输出
$env:PYTHONIOENCODING = 'utf-8'

$root    = 'D:\repository\skills\deploy-env'
$db      = Join-Path $root 'registry.sqlite'
$siteDir = Join-Path $root 'env-sites'
$py      = 'C:\Program Files\Python310\python.exe'

if (-not (Test-Path -LiteralPath $db)) { throw "registry.sqlite 不存在: $db" }

# ---- 1) 读注册表（python 内置 sqlite3，无 sqlite3 CLI；TSV 输出）----
$pyCode = @'
import sqlite3
con = sqlite3.connect(r'__DB__')
for r in con.execute('SELECT project,env,port,dist_root,backend_gateway,status FROM env_registry ORDER BY project,port'):
    print('\t'.join(str(x) for x in r))
con.close()
'@

$pyCode = $pyCode.Replace('__DB__', $db)
$tsv = & $py -c $pyCode
if ($LASTEXITCODE -ne 0) { throw "读取注册表失败 (python exit=$LASTEXITCODE)" }

$rows = @()
foreach ($line in $tsv) {
    if ([string]::IsNullOrWhiteSpace($line)) { continue }
    $c = $line -split "`t"
    if ($c.Count -lt 6) { throw "注册表行格式异常: $line" }
    $rows += [pscustomobject]@{
        Project = $c[0]; Env = $c[1]; Port = [int]$c[2]
        Dist = $c[3]; Gateway = $c[4]; Status = $c[5]
    }
}
if ($rows.Count -eq 0) { throw '注册表为空，未生成任何站点' }

# ---- 2) 端口冲突双保险（之二）：生成时重复端口报错 ----
$dups = $rows | Group-Object Port | Where-Object { $_.Count -gt 1 }
if ($dups) {
    throw "端口冲突（注册表存在重复端口）: " + (($dups | ForEach-Object { $_.Name }) -join ',')
}

# ---- 3) 片段模板（单引号 here-string，nginx 变量原样保留，占位符替换）----
$portalApi = @'
    # 静态资源缓存
    location ~* \.(js|css|png|jpg|jpeg|gif|ico|svg|woff|woff2|ttf|eot|map|json|pdf)$ {
        expires 7d;
        add_header Cache-Control "public" always;
        add_header X-Proxy-Target-Url "__GATEWAY__$request_uri" always;
        try_files $uri =404;
    }
    # 业务 API（统一打到本环境网关）
    location /api/v2.0/  { proxy_pass __GATEWAY__; }
    location /api/v3.0/  { proxy_pass __GATEWAY__; }
    location /v3.0/      { proxy_pass __GATEWAY__; }
    location /zhi2/      { proxy_pass __GATEWAY__; }
    location /zhi2-dev/  { proxy_pass __GATEWAY__; }
    location /zhi2-test/ { proxy_pass __GATEWAY__; }
'@
$fdcApi = @'
    # 静态资源缓存
    location ~* \.(js|css|png|jpg|jpeg|gif|ico|svg|woff|woff2|ttf|eot|map|json|xlsx)$ {
        expires 7d;
        add_header Cache-Control "public" always;
        try_files $uri =404;
    }
    # 业务 API：/api/v3.0 → /v3.0 后打到本环境网关
    location /api/v3.0/ {
        rewrite ^/api/v3.0/(.*)$ /v3.0/$1 break;
        proxy_pass __GATEWAY__;
    }
    location /zhi2/      { proxy_pass __GATEWAY__; }
    location /zhi2-dev/  { proxy_pass __GATEWAY__; }
    location /zhi2-test/ { proxy_pass __GATEWAY__; }
'@
$serverTpl = @'
# AUTO-GENERATED by gen_nginx_sites.ps1 — DO NOT EDIT BY HAND
# project=__PROJECT__  env=__ENV__  port=__PORT__  gateway=__GATEWAY__
server {
    listen __PORT__;
    server_name _;
    root __DIST__;
    index index.html;
    charset utf-8;
    client_max_body_size 100m;

    proxy_http_version 1.1;
    proxy_set_header Connection "";
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_connect_timeout 60s;
    proxy_send_timeout 120s;
    proxy_read_timeout 120s;

__API_LOCS__

    # SPA history 回退
    location / { try_files $uri $uri/ /index.html; }
    # 禁止访问隐藏文件
    location ~ /\. { deny all; }
}
'@

# ---- 4) 生成片段 ----
New-Item -ItemType Directory -Force -Path $siteDir | Out-Null
# 清理旧的生成片段，避免删除环境后残留
Get-ChildItem -LiteralPath $siteDir -Filter '*.conf' -File -ErrorAction SilentlyContinue | Remove-Item -Force

$enc = [System.Text.UTF8Encoding]::new($false)  # 无 BOM，避免 nginx 报 unknown directive
$generated = @()
foreach ($r in $rows) {
    if ($r.Status -ne 'enabled') { continue }
    $apiTpl = if ($r.Project -eq 'portal') { $portalApi } else { $fdcApi }
    $apiLocs = $apiTpl.Replace('__GATEWAY__', $r.Gateway)
    $conf = $serverTpl.Replace('__PROJECT__', $r.Project).Replace('__ENV__', $r.Env).Replace('__PORT__', [string]$r.Port).Replace('__GATEWAY__', $r.Gateway).Replace('__DIST__', $r.Dist).Replace('__API_LOCS__', $apiLocs)
    $file = Join-Path $siteDir ("{0}-{1}.conf" -f $r.Project, $r.Env)
    [System.IO.File]::WriteAllText($file, $conf, $enc)
    $generated += $file
}

Write-Output ("GENERATED={0}" -f $generated.Count)
$generated | ForEach-Object { Write-Output ("  " + $_) }
